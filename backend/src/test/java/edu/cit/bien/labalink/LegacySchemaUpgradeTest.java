package edu.cit.bien.labalink;

import edu.cit.bien.labalink.support.FakePaymentGateway;
import edu.cit.bien.labalink.support.TestInfrastructure;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Primary;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.mail.javamail.JavaMailSender;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import javax.sql.DataSource;
import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Databases created by pre-1.0 LabaLink used Hibernate ddl-auto=update.
 * This boots the full app (Flyway + Hibernate validate) on top of such a
 * schema with data in it, proving existing installs upgrade cleanly.
 */
@SpringBootTest
@ActiveProfiles("test")
class LegacySchemaUpgradeTest {

    @MockitoBean JavaMailSender mailSender;
    @Autowired JdbcTemplate jdbc;

    @TestConfiguration(proxyBeanMethods = false)
    static class LegacyDatabase {

        @Bean
        @Primary
        DataSource dataSource() throws Exception {
            var postgres = TestInfrastructure.postgres();
            try (Connection c = postgres.getPostgresDatabase().getConnection();
                 Statement s = c.createStatement()) {
                s.execute("DROP DATABASE IF EXISTS legacy");
                s.execute("CREATE DATABASE legacy");
            }
            DataSource legacy = postgres.getDatabase("postgres", "legacy");
            try (Connection c = legacy.getConnection();
                 Statement s = c.createStatement()) {
                s.execute(LEGACY_DDL);
                s.execute(LEGACY_DATA);
            }
            return legacy;
        }

        @Bean
        @Primary
        FakePaymentGateway fakePaymentGateway() {
            return new FakePaymentGateway();
        }
    }

    @Test
    void legacyDataSurvivesAndMoneyBecomesExactDecimal() {
        assertThat(jdbc.queryForObject(
                "select data_type from information_schema.columns "
                + "where table_name='users' and column_name='wallet_balance'",
                String.class))
            .isEqualTo("numeric");
        assertThat(jdbc.queryForObject(
                "select wallet_balance from users where email='old@test.local'",
                BigDecimal.class))
            .isEqualByComparingTo("12.35");
        assertThat(jdbc.queryForObject(
                "select auth_provider from users where email='google@test.local'",
                String.class))
            .isEqualTo("GOOGLE");
        assertThat(jdbc.queryForObject(
                "select count(*) from bookings", Integer.class))
            .isEqualTo(1);
    }

    // Shape of the schema Hibernate 6 generated for the old entities.
    private static final String LEGACY_DDL = """
        create table users (
            id bigint generated by default as identity primary key,
            created_at timestamp(6) not null,
            email varchar(255) not null unique,
            is_active boolean not null,
            password_hash varchar(255) not null,
            role varchar(255) not null check (role in ('CUSTOMER','ATTENDANT')),
            username varchar(255) not null,
            wallet_balance float(53) not null);
        create table machines (
            id bigint generated by default as identity primary key,
            created_at timestamp(6) not null,
            hourly_rate float(53) not null,
            machine_name varchar(255) not null,
            machine_type varchar(255) not null check (machine_type in ('WASHER','DRYER')),
            qr_token varchar(255) not null unique,
            status varchar(255) not null
                check (status in ('AVAILABLE','RUNNING','OUT_OF_ORDER')));
        create table bookings (
            id bigint generated by default as identity primary key,
            created_at timestamp(6) not null,
            end_time timestamp(6),
            start_time timestamp(6) not null,
            status varchar(255) not null
                check (status in ('PENDING','ACTIVE','COMPLETED','CANCELLED')),
            total_price float(53) not null,
            machine_id bigint not null references machines,
            user_id bigint not null references users);
        create table payments (
            id bigint generated by default as identity primary key,
            amount float(53) not null,
            created_at timestamp(6) not null,
            provider_reference varchar(255),
            status varchar(255) not null
                check (status in ('PENDING','SUCCESS','FAILED')),
            stripe_payment_intent_id varchar(255),
            user_id bigint not null references users);
        create table email_logs (
            id bigint generated by default as identity primary key,
            email_type varchar(255) not null,
            error_message varchar(255),
            sent_at timestamp(6) not null,
            status varchar(255) not null,
            subject varchar(255) not null,
            to_email varchar(255) not null);
        """;

    private static final String LEGACY_DATA = """
        insert into users (created_at, email, is_active, password_hash, role,
                           username, wallet_balance)
        values (now(), 'old@test.local', true, '$2a$10$abc', 'CUSTOMER', 'Old', 12.345),
               (now(), 'google@test.local', true, 'GOOGLE_AUTH_NO_PASSWORD',
                'CUSTOMER', 'Goog', 0);
        insert into machines (created_at, hourly_rate, machine_name, machine_type,
                              qr_token, status)
        values (now(), 25.0, 'Washer 1', 'WASHER', 'QR-ABC123', 'AVAILABLE');
        insert into bookings (created_at, start_time, status, total_price,
                              machine_id, user_id)
        values (now(), now(), 'COMPLETED', 25.0, 1, 1);
        insert into payments (amount, created_at, status, user_id)
        values (100.0, now(), 'SUCCESS', 1);
        """;
}
