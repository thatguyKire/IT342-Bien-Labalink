#!/usr/bin/env node
// Converts Lucide SVG icons (https://lucide.dev, ISC licence) into Android
// VectorDrawables, so the app and the web dashboard share one icon set.
//
//   node scripts/lucide-to-vector.mjs <dir-with-svgs> app/src/main/res/drawable
//
// Each <name>.svg becomes ic_<name>.xml (dashes become underscores). Icons
// are 24dp, 2dp round strokes, tinted with ?attr/colorControlNormal unless a
// view sets its own tint.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const [, , srcDir, outDir] = process.argv;
if (!srcDir || !outDir) {
  console.error('usage: lucide-to-vector.mjs <svg-dir> <drawable-dir>');
  process.exit(1);
}

const num = (v) => Number.parseFloat(v ?? '0');
const fmt = (n) => Number(n.toFixed(3)).toString();

function attrs(source) {
  const out = {};
  for (const [, key, value] of source.matchAll(/([\w-]+)="([^"]*)"/g)) {
    out[key] = value;
  }
  return out;
}

function points(list) {
  const nums = list.trim().split(/[\s,]+/).map(num);
  const pairs = [];
  for (let i = 0; i < nums.length; i += 2) pairs.push(`${fmt(nums[i])} ${fmt(nums[i + 1])}`);
  return pairs;
}

function ellipse(cx, cy, rx, ry) {
  return `M${fmt(cx - rx)} ${fmt(cy)}`
    + `A${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(cx + rx)} ${fmt(cy)}`
    + `A${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(cx - rx)} ${fmt(cy)}Z`;
}

function rect(a) {
  const x = num(a.x), y = num(a.y), w = num(a.width), h = num(a.height);
  const rx = Math.min(num(a.rx ?? a.ry), w / 2);
  const ry = Math.min(num(a.ry ?? a.rx), h / 2);
  if (!rx && !ry) return `M${fmt(x)} ${fmt(y)}H${fmt(x + w)}V${fmt(y + h)}H${fmt(x)}Z`;
  const arc = (ex, ey) => `A${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(ex)} ${fmt(ey)}`;
  return `M${fmt(x + rx)} ${fmt(y)}H${fmt(x + w - rx)}${arc(x + w, y + ry)}`
    + `V${fmt(y + h - ry)}${arc(x + w - rx, y + h)}H${fmt(x + rx)}`
    + `${arc(x, y + h - ry)}V${fmt(y + ry)}${arc(x + rx, y)}Z`;
}

function toPathData(tag, a) {
  switch (tag) {
    case 'path': return a.d;
    case 'circle': return ellipse(num(a.cx), num(a.cy), num(a.r), num(a.r));
    case 'ellipse': return ellipse(num(a.cx), num(a.cy), num(a.rx), num(a.ry));
    case 'rect': return rect(a);
    case 'line': return `M${fmt(num(a.x1))} ${fmt(num(a.y1))}L${fmt(num(a.x2))} ${fmt(num(a.y2))}`;
    case 'polyline': return `M${points(a.points).join('L')}`;
    case 'polygon': return `M${points(a.points).join('L')}Z`;
    default: throw new Error(`Unsupported element <${tag}>`);
  }
}

for (const file of readdirSync(srcDir).filter((f) => f.endsWith('.svg'))) {
  const name = basename(file, '.svg');
  const svg = readFileSync(join(srcDir, file), 'utf8');
  const paths = [...svg.matchAll(/<(path|circle|ellipse|rect|line|polyline|polygon)\b([^>]*?)\/?>/g)]
    .map(([, tag, body]) => toPathData(tag, attrs(body)))
    .map((d) => `    <path\n        android:pathData="${d}"\n`
      + '        android:strokeColor="#FF000000"\n'
      + '        android:strokeWidth="2"\n'
      + '        android:strokeLineCap="round"\n'
      + '        android:strokeLineJoin="round" />');

  const xml = '<?xml version="1.0" encoding="utf-8"?>\n'
    + `<!-- Lucide "${name}" (ISC licence), generated by scripts/lucide-to-vector.mjs -->\n`
    + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
    + '    android:width="24dp"\n    android:height="24dp"\n'
    + '    android:viewportWidth="24"\n    android:viewportHeight="24"\n'
    + '    android:tint="?attr/colorControlNormal">\n'
    + `${paths.join('\n')}\n</vector>\n`;
  writeFileSync(join(outDir, `ic_${name.replaceAll('-', '_')}.xml`), xml);
  console.log(`ic_${name.replaceAll('-', '_')}.xml`);
}
